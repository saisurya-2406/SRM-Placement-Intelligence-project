def parse_skills(value):
    if not isinstance(value, str):
        return set()
    return {token.strip().casefold() for token in value.split(",") if token.strip()}

df_sampled["parsed_student_skills"] = df_sampled["student_skills"].map(parse_skills)
df_sampled["parsed_required_skills"] = df_sampled["required_skills"].map(parse_skills)
df_sampled["matched_skill_set"] = [a & b for a, b in zip(df_sampled.parsed_student_skills, df_sampled.parsed_required_skills)]
df_sampled["missing_skill_set"] = [required - student for required, student in zip(df_sampled.parsed_required_skills, df_sampled.parsed_student_skills)]
df_sampled["engineered_student_skill_count"] = df_sampled.parsed_student_skills.map(len)
df_sampled["engineered_required_skill_count"] = df_sampled.parsed_required_skills.map(len)
df_sampled["engineered_matched_skill_count"] = df_sampled.matched_skill_set.map(len)
df_sampled["engineered_missing_skill_count"] = df_sampled.missing_skill_set.map(len)
df_sampled["engineered_skill_match_pct"] = np.divide(
    df_sampled.engineered_matched_skill_count * 100.0,
    df_sampled.engineered_required_skill_count,
    out=np.zeros(len(df_sampled), dtype=float),
    where=df_sampled.engineered_required_skill_count.to_numpy() > 0,
)
all_missing_skills = []
for required, student in zip(df_sampled["parsed_required_skills"], df_sampled["parsed_student_skills"]):
    all_missing_skills.extend(required - student)
top_skill_gaps = pd.Series(Counter(all_missing_skills), dtype="int64").sort_values(ascending=False).head(15)
print("Most frequent missing skills in the deterministic sample:")
