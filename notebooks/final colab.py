"""## Exploratory checks and skill-gap analysis

Skill tokens are stripped, lowercased, and converted to sets. That makes matching case-insensitive and removes duplicates; missing/empty text becomes an empty set. The per-record missing-skill count is required skills minus student skills.
"""

